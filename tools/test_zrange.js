// Matter doesn't depend on where it is: items and units are compared by type and kind summed over the levels (a unit
// that walks up a ramp takes its pack with it; the base commit's own two runs differ only there). Strata and objects are
// per material and type on the core levels.
const byType = o => { const out = {}; for (const k in o || {}) { const t = k.replace(/:-?\d+$/, ""); out[t] = (out[t] || 0) + o[k]; } return out; };
function censusDiff(a, b) {
    const out = [];
    for (const key of ["strata", "objects", "items", "units"]) {
        const ka = key === "items" || key === "units" ? byType(a[key]) : a[key] || {}, kb = key === "items" || key === "units" ? byType(b[key]) : b[key] || {};
        for (const k of new Set([...Object.keys(ka), ...Object.keys(kb)])) if ((ka[k] || 0) !== (kb[k] || 0)) out.push(`${key}.${k}: ${ka[k] || 0} vs ${kb[k] || 0}`);
    }
    return out;
}
/** The census as ledger registrations: strata by material, objects and items by their catalog class where one maps. */
function ledgerTotals(census, ledgerPath) {
    const { createLedger } = require(ledgerPath);
    const led = createLedger();
    const unmapped = {};
    const put = (cls, form, n, what) => { if (!n) return; try { led.register(cls, form, n, what); } catch (e) { unmapped[what] = (unmapped[what] || 0) + n; } };
    const MAT = { 1: "stone", 2: "soil", 3: "wood", 4: "water", 5: "lava" };
    for (const k in census.strata) {
        const b = Number(k), id = b & 63, built = (b & 0x80) !== 0, cls = MAT[id];
        if (!cls) { unmapped[`strata:${k}`] = census.strata[k]; continue; }
        const form = cls === "water" || cls === "lava" ? "fluid" : built ? "object" : "strata";
        put(cls, form, census.strata[k], `strata:${k}`);
    }
    if (census.capStrata) put("stone", "strata", census.capStrata, "caps above +2");
    for (const k in census.objects) unmapped[`object:${k}`] = census.objects[k];   // objects and items keep their own counts (compared raw)
    for (const k in census.items) unmapped[`item:${k}`] = census.items[k];
    led.seal();
    return { totals: led.totals().classes, families: led.totals().families, checksum: led.checksum(), unmappedKeys: Object.keys(unmapped).length };
}

function evaluate(results, base, provoked) {
    const out = {};
    const cfgs = Object.keys(results).filter(k => k !== "__legacy");
    const inGame = (cfg, phase, name) => { const r = results[cfg][phase]; return r && r.checks[name] ? r.checks[name] : { pass: false, detail: `the check ${name} did not run (${r ? r.result : "no run"})` }; };
    const reportOf = (cfg, phase) => (results[cfg][phase] && results[cfg][phase].report ? results[cfg][phase].report.data : null);

    // single_authority: the static scan (on this tree or the provocation's edited copy) and every range's probe.
    {
        const root = provoked && provoked.scanRoot ? provoked.scanRoot : ROOT;
        const s = judge(scan(root), loadAllow(path.join(ZR, "z_literal_allowlist.json")));
        const probes = cfgs.map(c => ({ c, r: inGame(c, "core", "single_authority_ingame") }));
        out.single_authority = { pass: s.bad.length === 0 && s.stale.length === 0 && probes.every(p => p.r.pass),
            detail: `static scan: ${s.hits} lines with a Z pattern, ${s.allowed} allowed (${s.entries} entries), ${s.bad.length} not allowed${s.bad.length ? ` (${s.bad.slice(0, 3).map(h => `${h.file}:${h.line} ${h.text.slice(0, 60)}`).join(" | ")})` : ""}, ${s.stale.length} stale; in-game: ${probes.map(p => `${p.c} ${p.r.pass ? "PASS" : "FAIL"}`).join(", ")}` };
    }
    out.elevation_math = { pass: cfgs.every(c => inGame(c, "core", "elevation_math").pass), detail: cfgs.map(c => `${c}: ${inGame(c, "core", "elevation_math").detail.slice(0, 220)}`).join(" || ") };
    {
        const want2 = blastTable(2), want1 = blastTable(1), rows = [];
        let ok = true;
        for (const c of cfgs) {
            const d = reportOf(c, "core"), k = inGame(c, "core", "feet_constants");
            const got = d && d.blast && d.blast.radii;
            const same = !!got && [3, 5, 7].every(R => JSON.stringify(got[R].hits) === JSON.stringify(want2[R]));
            if (!(k.pass && same)) ok = false;
            rows.push(`${c}: constants ${k.pass ? "ok" : "WRONG"}, blast ${same ? "= 2 ft table" : "DIFFERS from the 2 ft table"} (${got ? [3, 5, 7].map(R => `r${R} ${got[R].hits.length}`).join(", ") : "none"})`);
        }
        const bb = base && base.blast && base.blast.radii;
        const baseSame = !!bb && [3, 5, 7].every(R => JSON.stringify(bb[R].hits) === JSON.stringify(want1[R]));
        out.feet_2ft_10ft = { pass: ok && baseSame, detail: `${rows.join("; ")}; base ${sha8(BASE)}: ${baseSame ? "= 1 ft table" : "DIFFERS from the 1 ft table"} (${bb ? [3, 5, 7].map(R => `r${R} ${bb[R].hits.length}`).join(", ") : "no base data"}); tables: 2 ft ${[3, 5, 7].map(R => `r${R} ${want2[R].length}`).join(", ")}, 1 ft ${[3, 5, 7].map(R => `r${R} ${want1[R].length}`).join(", ")} strata` };
    }
    {
        const rows = [];
        let ok = cfgs.every(c => inGame(c, "core", "sparse_outer_uniform").pass && inGame(c, "core", "sparse_split_one_chunk").pass);
        const big = cfgs.find(c => c === "-16..15"), leg = cfgs.find(c => c === "-2..2");
        if (big && leg) {
            const a = reportOf(big, "core"), b = reportOf(leg, "core");
            if (a && b && a.sparse && b.sparse) {
                const bound = memoryBound(a, b);
                const diff = bound.tall - bound.legacy;
                const heapDiff = a.heapAfterNewGame && b.heapAfterNewGame ? a.heapAfterNewGame.usedJSHeapSize - b.heapAfterNewGame.usedJSHeapSize : null;
                if (!(diff <= bound.bytes)) ok = false;
                rows.push(`baseline store (directories, MIXED arrays, caps) -16..+15 ${bound.tall} B, -2..+2 ${bound.legacy} B: difference ${diff} B, bound ${bound.bytes} B (${bound.derivation}); shape grids cached ${a.memory.shapeGrids} / ${b.memory.shapeGrids} B; JS heap after New Game (forced GC ${a.heapAfterNewGame.gc}): ${a.heapAfterNewGame.usedJSHeapSize} vs ${b.heapAfterNewGame.usedJSHeapSize} B (difference ${heapDiff} B, reported, not judged)`);
            } else { ok = false; rows.push("no storage numbers from -16..15 and -2..2"); }
        } else rows.push("(the -16..15 minus -2..2 bound needs both configurations)");
        rows.unshift(cfgs.map(c => `${c}: outer ${inGame(c, "core", "sparse_outer_uniform").pass ? "UNIFORM" : "WRONG"}, split ${inGame(c, "core", "sparse_split_one_chunk").pass ? "one chunk" : "WRONG"}`).join(", "));
        out.sparse_memory = { pass: ok, detail: rows.join("; ") };
    }
    {
        let ok = cfgs.every(c => inGame(c, "play", "sparse_save_changes").pass);
        const rows = [cfgs.map(c => `${c}: changes ${inGame(c, "play", "sparse_save_changes").pass ? "one record each, round trip ok" : "WRONG"}`).join(", ")];
        const big = cfgs.find(c => c === "-16..15"), nine = cfgs.find(c => c === "-4..4");
        if (big && nine) {
            const a = reportOf(big, "play"), b = reportOf(nine, "play");
            if (a && b) {
                const part = s => s.levels + s.zRange + s.fluid + s.fluidAlias;
                const diff = part(a.saveFresh) - part(b.saveFresh);
                if (!(diff <= SAVE_BOUND)) ok = false;
                rows.push(`fresh world, terrain and fluid parts (levels + zRange + fluid): -16..+15 ${part(a.saveFresh)} B, -4..+4 ${part(b.saveFresh)} B: difference ${diff} B (bound ${SAVE_BOUND} B); whole saves ${a.saveFresh.total} / ${b.saveFresh.total} characters`);
            } else { ok = false; rows.push("no save numbers"); }
        } else rows.push("(the 256 B bound needs -16..15 and -4..4)");
        out.sparse_save = { pass: ok, detail: rows.join("; ") };
    }
    {
        const r = results.__legacy;
        const c = r && r.checks.legacy_save_loads;
        out.legacy_save_loads = { pass: !!c && c.pass, detail: c ? c.detail.slice(0, 900) : `did not run (${r ? r.result : "no legacy run"})` };
    }
    {
        const rows = [];
        let ok = !!(base && base.core);
        for (const c of cfgs) {
            const d = reportOf(c, "core");
            const bad = [];
            if (!d || !d.core) { ok = false; rows.push(`${c}: no data`); continue; }
            for (const part of ["checksums", "regenerated", "baseline", "cells", "shapes"]) if (JSON.stringify(d.core[part]) !== JSON.stringify(base && base.core[part])) bad.push(part);
            if (bad.length) ok = false;
            rows.push(`${c}: ${bad.length ? `DIFFERENT ${bad.join(", ")} (${JSON.stringify(d.core.baseline)} vs ${JSON.stringify(base && base.core.baseline)})` : `identical (checksums ${Object.values(d.core.checksums).join(" ")})`}`);
        }
        out.old_layers_identical = { pass: ok, detail: `base ${sha8(BASE)} seed ${SEED}: ${rows.join("; ")}` };
    }
    {
        const rows = [];
        let ok = !!(base && base.census);
        const ledgerPath = path.join(provoked && provoked.clone ? provoked.clone : ROOT, "game", "js", "sim", "ledger.js");
        const lb = base && base.census ? ledgerTotals(base.census, ledgerPath) : null, lba = base && base.censusAfter ? ledgerTotals(base.censusAfter, ledgerPath) : null;
        for (const c of cfgs) {
            const d0 = reportOf(c, "core"), d1 = reportOf(c, "sim");
            if (!lb || !lba) { ok = false; rows.push(`${c}: no base census to compare with`); continue; }
            if (!d0 || !d0.census || !d1 || !d1.censusAfter) { ok = false; rows.push(`${c}: no census`); continue; }
            const diff0 = censusDiff(d0.census, base.census), diff1 = censusDiff(d1.censusAfter, base.censusAfter);
            const caps0 = d0.census.capStrata === base.census.capStrata;
            const l0 = ledgerTotals(d0.census, ledgerPath), l1 = ledgerTotals(d1.censusAfter, ledgerPath);
            const led0 = l0.checksum === lb.checksum, led1 = l1.checksum === lba.checksum;
            if (diff0.length || diff1.length || !caps0 || !led0 || !led1) ok = false;
            rows.push(`${c}: New Game ${diff0.length ? `DIFFERS (${diff0.slice(0, 4).join(", ")})` : "identical"}, rock above +2 ${d0.census.capStrata} strata (base caps ${base.census.capStrata}), ledger ${l0.checksum} (base ${lb.checksum}); ` +
                `after ${d1.simulation ? d1.simulation.updates : "?"} updates ${diff1.length ? `DIFFERS (${diff1.slice(0, 4).join(", ")})` : "identical"}, ledger ${l1.checksum} (base ${lba.checksum}); layers outside -2..+2: ${Object.keys(d0.census.outer || {}).length} material keys`);
        }
        out.matter_unchanged = { pass: ok, detail: `base ${sha8(BASE)} seed ${SEED} (base repeat: census ${base && base.repeat ? base.repeat.censusSame : "?"}, after play ${base && base.repeat ? base.repeat.censusAfterSame : "?"}): ${rows.join("; ")}` };
    }
    out.extreme_layers_work = { pass: cfgs.every(c => inGame(c, "play", "extreme_layers_work").pass && inGame(c, "play", "no_errors").pass && inGame(c, "core", "no_errors").pass),
        detail: cfgs.map(c => `${c}: ${inGame(c, "play", "extreme_layers_work").pass ? "PASS" : "FAIL"} ${inGame(c, "play", "extreme_layers_work").detail.slice(0, 400)}; errors core ${inGame(c, "core", "no_errors").pass ? "none" : "SOME"}, play ${inGame(c, "play", "no_errors").pass ? "none" : "SOME"}`).join(" || ") };
    out.path_scratch_bounded = { pass: cfgs.every(c => inGame(c, "core", "path_scratch_bounded").pass), detail: cfgs.map(c => `${c}: ${inGame(c, "core", "path_scratch_bounded").detail.slice(0, 260)}`).join(" || ") };
    return out;
}

