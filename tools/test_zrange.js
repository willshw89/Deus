/** Delete a folder without following junctions (snapshot asset folders are junctions to the real ones). */
function removeTree(dir) {
    if (!fs.existsSync(dir)) return;
    if (fs.lstatSync(dir).isSymbolicLink()) { fs.unlinkSync(dir); return; }
    for (const e of fs.readdirSync(dir)) {
        const p = path.join(dir, e), l = fs.lstatSync(p);
        if (l.isSymbolicLink()) fs.unlinkSync(p);
        else if (l.isDirectory()) removeTree(p);
        else fs.rmSync(p, { force: true });
    }
    fs.rmdirSync(dir);
}
/** A snapshot of <gameDir> under %TEMP%: js/, data/, index.html, package.json copied, the rest junctions (tools/test_snapshot.js's pattern). */
function makeSnapshot(gameDir, tag, edits) {
    const dir = path.join(os.tmpdir(), "laneaa_zr_snap", `${tag}_${process.pid}_${Date.now()}`);
    removeTree(dir);
    fs.mkdirSync(dir, { recursive: true });
    const COPY = ["js", "data", "index.html", "package.json"];
    for (const e of fs.readdirSync(gameDir, { withFileTypes: true })) {
        const src = path.join(gameDir, e.name), dst = path.join(dir, e.name);
        if (["test_output", "save", "game_runtime.log", "test_screenshot.png"].includes(e.name)) continue;
        if (COPY.includes(e.name)) fs.cpSync(src, dst, { recursive: true });
        else if (e.isDirectory()) fs.symlinkSync(src, dst, "junction");
        else fs.copyFileSync(src, dst);
    }
    fs.mkdirSync(path.join(dir, "test_output"), { recursive: true });
    // Provocation edits: exact source edits, each target exactly once.
    for (const [file, from, to] of edits || []) {
        const p = path.join(dir, "js", "plugins", file);
        const src = fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");
        const n = src.split(from).length - 1;
        if (n !== 1) throw new Error(`provocation edit: target occurs ${n} times in ${file}: ${from.slice(0, 80)}`);
        fs.writeFileSync(p, src.replace(from, () => to));
    }
    fs.writeFileSync(path.join(dir, "js", "plugins", "DEUS_TestZRange.js"),
        `// Test-only plugin written by tools/test_zrange.js into a snapshot copy. Never part of the game.\n(${zrangeSuitePlugin.toString()})();\n`);
    const pj = path.join(dir, "js", "plugins.js");
    const text = fs.readFileSync(pj, "utf8").replace(/^﻿/, "");
    const plugins = JSON.parse(text.slice(text.indexOf("["), text.lastIndexOf("]") + 1));
    const world = plugins.find(p => p.name === "DEUS_World");
    if (!world) throw new Error("DEUS_World is not in plugins.js");
    world.parameters = Object.assign({}, world.parameters, { Seed: String(SEED) });
    if (!plugins.some(p => p.name === "DEUS_Test" && p.status)) throw new Error("DEUS_Test is not registered");
    plugins.push({ name: "DEUS_TestZRange", status: true, description: "[test only] WG.00.17 zrange suite", parameters: {} });
    fs.writeFileSync(pj, `// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n${plugins.map(p => JSON.stringify(p)).join(",\n")}\n];\n`);
    // A forced garbage collection for the heap numbers: --expose-gc in the snapshot's chromium args (the snapshot only).
    const pk = path.join(dir, "package.json");
    const pkg = JSON.parse(fs.readFileSync(pk, "utf8"));
    pkg["chromium-args"] = `${pkg["chromium-args"] || ""} --js-flags=--expose-gc`.trim();
    fs.writeFileSync(pk, JSON.stringify(pkg, null, 2));
    return dir;
}
/** One NW.js run of the suite on a snapshot: resolves { status, checks: { name: { pass, detail } }, result, report, text, secs }. */
async function runPhase(clone, label, env, edits) {
    const gameDir = path.join(clone, "game");
    const snap = makeSnapshot(gameDir, label.replace(/[^\w.-]/g, "_"), edits);
    const t0 = Date.now();
    const e = Object.assign({}, process.env, env, { ZR_UPDATES: String(UPDATES) });
    if (env.DEUS_Z_RANGE === null) delete e.DEUS_Z_RANGE;
    const r = await new Promise(resolve => {
        const child = spawn(process.execPath, [path.join(clone, "tools", "run_tests.js"), "zrange", "--game", snap], { env: e, stdio: ["ignore", "pipe", "pipe"] });
        child.stdout.on("data", () => {});
        child.stderr.on("data", () => {});
        const timer = setTimeout(() => { try { child.kill(); } catch (_) { /* gone */ } }, RUN_TIMEOUT);
        child.on("exit", status => { clearTimeout(timer); resolve({ status }); });
    });
    const out = path.join(snap, "test_output");
    const text = fs.existsSync(path.join(out, "results.txt")) ? fs.readFileSync(path.join(out, "results.txt"), "utf8") : "";
    let report = null;
    try { report = JSON.parse(fs.readFileSync(path.join(out, "zrange_report.json"), "utf8")); } catch (_) { report = null; }
    const checks = {};
    for (const m of text.matchAll(/^(PASS|FAIL) zrange\.(\w+)(?: - (.*))?$/gm)) checks[m[2]] = { pass: m[1] === "PASS", detail: m[3] || "" };
    const result = (text.match(/^RESULT: .*$/m) || [null])[0];
    const secs = ((Date.now() - t0) / 1000).toFixed(0);
    const ev = arg("evidence", "");
    if (ev) {
        const dst = path.join(path.resolve(ev), label.replace(/[^\w.-]/g, "_"));
        fs.mkdirSync(dst, { recursive: true });
        for (const f of fs.existsSync(out) ? fs.readdirSync(out) : []) if (f === "results.txt" || f === "zrange_report.json" || (f.startsWith("zrange.") && f.endsWith(".png"))) fs.copyFileSync(path.join(out, f), path.join(dst, f));
    }
    if (!KEEP) { try { removeTree(snap); } catch (err) { log(`  (could not delete ${snap}: ${err.message})`); } }
    log(`  run ${label}: ${result || "NO RESULT LINE"} in ${secs} s (run_tests exit ${r.status}); snapshot ${snap}${KEEP ? "" : " (deleted)"}`);
    for (const line of text.split(/\r?\n/)) if (/^(FAIL|ERROR|HARNESS)/.test(line)) log(`    ${line.slice(0, 400)}`);
    return { status: r.status, checks, result, report, text, secs, snap };
}

