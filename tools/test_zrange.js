/**
 * tools/test_zrange.js - WG.00.17 lane AA: the Z range as one setting, 32 layers (-16..+15), sparse storage in memory
 * and saves, 2 ft strata / 10 ft layers / 5 ft squares, the 9-layer test mode and old 5-level saves.
 *
 * Runs the real game in NW.js on per-run snapshot copies of game/ under %TEMP% (printed, deleted after), with a
 * test-only plugin (DEUS_TestZRange.js, the suite "zrange", tools/zrange/zrange_suite.js) and a pinned world seed.
 * Each configuration (a Z range, passed to the game as DEUS_Z_RANGE) runs the phases core and play in their own NW.js
 * runs (DEUS_Test stops a run after 180 s); the legacy phase loads a save written by the base commit.
 *
 * Checks (PASS/FAIL lines, then RESULT). Each has a provocation (--provoke) that must make it FAIL:
 *   single_authority      the static scan finds no Z literal outside the allow-list (tools/zrange/scan_z_literals.js) and,
 *                         at each range, the in-game probe accepts exactly zMin..zMax (isLevel, inWorld, map ids, labels,
 *                         addUnit, Items.drop, Objects.setIn, strataAt, shapeAt, the level list)
 *   elevation_math        e = (z - zMin) * 5 + s both ways on the lowest, highest and core levels, no cap at 24
 *   feet_2ft_10ft         UF.Space is 5 ft / 2 ft / 5 strata / 10 ft, and the blast fixture's destroyed strata equal the
 *                         2 ft table at the tip (tools/zrange/blast_tables.js) and the 1 ft table at the base commit
 *   sparse_memory         outside -2..+2 every chunk is UNIFORM except the mountain rock above +2 (counted), a first
 *                         write to a sky cell splits one chunk, and the baseline storage at -16..+15 minus -2..+2 stays
 *                         within the bound derived from the directory size (tools/zrange/bounds.js)
 *   sparse_save           a fresh world's save at -16..+15 is at most 256 B larger in its terrain and fluid parts than
 *                         at -4..+4; a change on +12 and on -14 adds only its record; save and load round-trip the cells
 *   legacy_save_loads     a save written by the base commit loads at -2..+2 with every cell, unit and item identical, and
 *                         stays at -2..+2 after another save and load
 *   old_layers_identical  the core levels -2..+2 of the pinned seed: checksums, generated bytes and every cell's strata
 *                         and shape identical to the base commit's, at every range
 *   matter_unchanged      the census (strata by material on -2..+2, the rock above +2 against the base's caps, objects,
 *                         items, units) and the ledger's totals per class (game/js/sim/ledger.js, read only) identical to
 *                         the base commit's after New Game and after ZR_UPDATES map updates
 *   extreme_layers_work   on the top and bottom levels a unit stands, walks and paths, the view switches there in place
 *                         and view stepping stops at the ends, no errors
 *   path_scratch_bounded  a 3D search on one level allocates scratch for the levels it reached only (counted)
 *
 * Usage: node tools/test_zrange.js [--z-range=<zMin>..<zMax>] [--seed=18] [--base=<sha>] [--updates=3000]
 *                                  [--refresh-base] [--make-legacy-fixture] [--provoke=<check> | --provoke-all]
 *                                  [--evidence=<dir>] [--keep] [--jobs=n]
 *   (no --z-range: the three configurations -4..4, -16..15 and the legacy -2..2)
 *   --refresh-base          run the base commit (a temp clone) and rewrite tools/zrange/fixtures/base_<sha8>_seed<n>.json
 *   --make-legacy-fixture   run make_legacy on the base commit and write tools/zrange/fixtures/legacy_save_<sha8>_seed<n>.json.gz
 *   --phase=<p> [--commit=<sha>]  run one phase (core, play, sim, legacy) on the configurations (default: this tree; with
 *                           --commit, a temp clone of that commit) and print the suite's lines and report (diagnostics)
 * Exit: 0 all checks passed (with --provoke: every provocation caught); 1 a check failed / a provocation not caught;
 *       2 harness problem.
 */
