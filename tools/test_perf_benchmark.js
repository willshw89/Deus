"use strict";

const { spawn } = require("child_process");
const path = require("path");
const fs = require("fs");

console.log("=== DEUS-PERF-01: 4x Speed / 60 FPS Native Benchmark Runner ===");

const NW = "C:\\Program Files (x86)\\Steam\\steamapps\\common\\RPG Maker MZ\\nwjs-win\\nw.exe";
const gameDir = path.resolve(__dirname, "..", "game");
const resultsFile = path.join(gameDir, "test_output", "results.txt");

if (!fs.existsSync(NW)) {
    console.error(`ERROR: nw.exe not found at ${NW}`);
    process.exit(2);
}

fs.rmSync(resultsFile, { force: true });

const profile = path.join(require("os").tmpdir(), `deus_perf_profile_${Date.now()}`);
const flag = "--deus-test=native_perf_4x_benchmark";

console.log(`Launching NW.js with ${flag} on ${gameDir}...`);
const noThrottle = [
    "--disable-background-timer-throttling",
    "--disable-renderer-backgrounding",
    "--disable-backgrounding-occluded-windows",
    "--disable-features=CalculateNativeWinOcclusion"
];

const child = spawn(NW, [gameDir, `--user-data-dir=${profile}`, ...noThrottle, flag], {
    stdio: ["ignore", "pipe", "pipe"]
});

const TIMEOUT_MS = 60000; // 60s max
const timer = setTimeout(() => {
    console.error(`HARNESS TIMEOUT: nw.exe did not exit within ${TIMEOUT_MS / 1000}s, terminating.`);
    child.kill();
}, TIMEOUT_MS);

child.on("exit", (code, signal) => {
    clearTimeout(timer);
    try { fs.rmSync(profile, { recursive: true, force: true }); } catch (_) {}

    if (!fs.existsSync(resultsFile)) {
        console.error("ERROR: No results.txt generated by harness.");
        process.exit(2);
    }

    const text = fs.readFileSync(resultsFile, "utf8");
    console.log("\n--- BENCHMARK RESULTS ---");
    console.log(text);

    const m = text.match(/^RESULT: (\d+) passed, (\d+) failed \(exit (\d)\)$/m);
    if (!m) {
        console.error("ERROR: Malformed results.txt (no RESULT summary).");
        process.exit(2);
    }

    const passed = parseInt(m[1], 10);
    const failed = parseInt(m[2], 10);
    const exitCode = parseInt(m[3], 10);

    if (failed === 0 && exitCode === 0) {
        console.log("=== PERF-01 BENCHMARK PASSED (60 FPS @ 4x Speed Validated) ===");
        process.exit(0);
    } else {
        console.error(`=== PERF-01 BENCHMARK FAILED (${failed} budget violations) ===`);
        process.exit(1);
    }
});

